CREATE TABLE IF NOT EXISTS survey_responses (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  response_id CHAR(36) NOT NULL UNIQUE,
  variant ENUM('A','B') NOT NULL,
  initial_price DECIMAL(6,2) NOT NULL,
  age TINYINT UNSIGNED NOT NULL,
  location_clermont TINYINT(1) NOT NULL DEFAULT 1,
  consent TINYINT(1) NOT NULL DEFAULT 1,
  intent_initial TINYINT UNSIGNED NOT NULL,
  followup_price DECIMAL(6,2) NOT NULL,
  intent_followup TINYINT UNSIGNED NOT NULL,
  p_too_cheap DECIMAL(6,2) NOT NULL,
  p_cheap DECIMAL(6,2) NOT NULL,
  p_expensive DECIMAL(6,2) NOT NULL,
  p_too_expensive DECIMAL(6,2) NOT NULL,
  control_price VARCHAR(20) NOT NULL,
  control_correct TINYINT(1) NOT NULL,
  qualitative_reason VARCHAR(80) NOT NULL,
  perceived_value TINYINT UNSIGNED NOT NULL,
  perceived_quality TINYINT UNSIGNED NOT NULL,
  perceived_trust TINYINT UNSIGNED NOT NULL,
  status ENUM('Etudiant','Jeune actif','Autre') NOT NULL,
  completion_ms INT UNSIGNED NOT NULL,
  submitted_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_variant (variant),
  INDEX idx_status (status),
  INDEX idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;